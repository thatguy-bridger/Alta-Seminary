// Writes manifest.js: every image that ships with the site and belongs in the image library, with its credit, tags and alt text.
// The paintings come from the same data the site itself uses (src/makeup/thumbnails.js and art.js), so nothing is typed twice.
//   node scripts/gallery-backfill/make-manifest.mjs
import { writeFileSync } from 'node:fs';
import { PAINTINGS } from '../../src/makeup/thumbnails.js';
import { ART } from '../../src/makeup/art.js';

const credit = (a, year) => `${a}${year ? `, ${year}` : ''}. Public domain, from Wikimedia Commons.`;
const last = (name) => name.split(' ').pop().toLowerCase();
const items = [
  ...PAINTINGS.map((p) => ({
    path: p.src, title: `${p.title}, ${p.artist}${p.year ? `, ${p.year}` : ''}`, alt: p.alt,
    description: `A painting used as a lesson picture in Makeup Work: ${p.title} by ${p.artist}.`,
    tags: ['painting', 'savior', 'makeup', 'lesson', last(p.artist)], credit: credit(p.artist, p.year), license: 'Public domain',
  })),
  ...Object.entries(ART).map(([step, a]) => ({
    path: a.src, title: `${a.title}, ${a.artist}${a.year ? `, ${a.year}` : ''}`, alt: a.alt,
    description: `A painting shown at the top of the "${step}" step of Makeup Work: ${a.title} by ${a.artist}.`,
    tags: ['painting', 'savior', 'makeup', 'banner', step, last(a.artist)], credit: credit(a.artist, a.year), license: 'Public domain',
  })),
  ...['a', 'b'].map((k) => ({
    path: `/makeup/mountains-${k}.webp`, title: `Mountain scene ${k.toUpperCase()}`, alt: '',
    description: 'Mountain artwork behind the Makeup Work journey, cut from the site banners and recolored from night to morning.',
    tags: ['makeup', 'background', 'mountains'], credit: 'Alta Seminary', license: 'Alta Seminary artwork',
  })),
  { path: '/og-default.png', title: 'Default social share image', alt: 'Alta Seminary', description: 'The picture shown when a page without its own share image is shared.', tags: ['site', 'social'], credit: 'Alta Seminary', license: 'Alta Seminary artwork' },
];
writeFileSync(new URL('./manifest.js', import.meta.url), `// Generated by make-manifest.mjs. Do not edit by hand.\nexport const MANIFEST = ${JSON.stringify(items, null, 2)};\n`);
console.log(`${items.length} images`);
